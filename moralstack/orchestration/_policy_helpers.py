CONSTRAINED_GENERATION_INSTRUCTION = _DEFAULT.text("policy.constrained_instruction")


def sanitize_policy_output(text: str) -> str:
    """Removes leakage/meta-instructions from the text generated by the policy."""
    if not text:
        return text
    lines = text.splitlines()
    cleaned: list[str] = []
    bad_markers = [
        "rule of thumb",
        "system prompt",
        "developer message",
        "you are a helpful ai",
        "i am a helpful ai",
        "sono un assistente ai",
        "always and only",
        "do not add translations",
    ]
    for i, line in enumerate(lines):
        s = line.strip()
        if i < 8:
            low = s.lower()
            if any(m in low for m in bad_markers):
                continue
            if re.search(r"\b(ALWAYS|ONLY|DO NOT|RULE OF THUMB)\b", s):
                continue
        cleaned.append(line)
    out = "\n".join(cleaned).strip()
    return out if out else text.strip()
